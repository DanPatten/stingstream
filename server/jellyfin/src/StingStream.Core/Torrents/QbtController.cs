    /// <summary>
    /// Create a category.
    /// </summary>
    /// <remarks>
    /// Part of the arrs' "Test": if the configured category is missing they create it here and
    /// then re-read <c>torrents/categories</c>, failing the test outright if it still is not
    /// there. So this has to actually persist.
    /// </remarks>
    [HttpPost("torrents/createCategory")]
    public async Task<IActionResult> CreateCategory(CancellationToken cancellationToken)
    {
        var unauthorised = Unauthorised();
        if (unauthorised is not null)
        {
            return unauthorised;
        }

        var form = await Request.ReadFormAsync(cancellationToken).ConfigureAwait(false);
        var name = form["category"].ToString();
        if (string.IsNullOrWhiteSpace(name))
        {
            return BadRequest();
        }

        // Same containment rule as an add: a category is a directory this node will create and
        // write into, so the caller does not get to name one outside the torrent root.
        var savePath = form["savePath"].ToString();
        if (!string.IsNullOrWhiteSpace(savePath) && !SafePath.IsUnder(_engine.Root, savePath))
        {
            _logger.LogWarning(
                "Refusing a qBittorrent category with a save path outside the torrent root: {Path}",
                savePath);
            return BadRequest();
        }

        await _engine.CreateCategoryAsync(name, string.IsNullOrWhiteSpace(savePath) ? null : savePath, cancellationToken)
            .ConfigureAwait(false);
        return Ok();
    }

