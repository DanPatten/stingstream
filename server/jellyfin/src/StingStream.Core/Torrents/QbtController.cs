    /// <summary>
    /// Client preferences.
    /// </summary>
    /// <remarks>
    /// The arrs read exactly ten fields from this and validate two things with them: that the
    /// client is not configured to delete completed downloads before they can be imported
    /// (<c>max_ratio_enabled</c> / <c>max_seeding_time_enabled</c> combined with
    /// <c>max_ratio_act</c>), and that queueing is on when a non-default download priority is set.
    /// Every limit here is therefore reported as disabled: StingStream keeps seeding until the arr
    /// says the download may go.
    /// </remarks>
    [HttpGet("app/preferences")]
    public IActionResult Preferences()
    {
        var unauthorised = Unauthorised();
        if (unauthorised is not null)
        {
            return unauthorised;
        }

        var settings = new JsonObject
        {
            ["save_path"] = _engine.Root,
            ["temp_path_enabled"] = false,
            ["temp_path"] = _engine.Root,
            ["max_ratio_enabled"] = false,
            ["max_ratio"] = -1,
            ["max_seeding_time_enabled"] = false,
            ["max_seeding_time"] = -1,
            ["max_inactive_seeding_time_enabled"] = false,
            ["max_inactive_seeding_time"] = -1,
            // 0 = Pause. Never Remove or DeleteFiles: an engine that deletes a download on its own
            // schedule can delete it before the arr has imported it.
            ["max_ratio_act"] = 0,
            ["queueing_enabled"] = true,
            ["dht"] = DhtEnabled(),
            ["pex"] = true,
            ["lsd"] = true,
            ["auto_tmm_enabled"] = false,
            ["create_subfolder_enabled"] = true,
            ["start_paused_enabled"] = false,
        };
        return new JsonResult(settings);
    }

    private bool DhtEnabled()
    {
        // Reported honestly rather than hard-coded true. With DHT off the arrs refuse a
        // trackerless magnet immediately, which is the right answer -- this engine genuinely
        // cannot fetch one -- instead of accepting it and stalling in metaDL forever.
        return HttpContext.RequestServices
            .GetService(typeof(Data.SettingsStore)) is Data.SettingsStore store
            && store.Get().DownloadClients.TorrentDhtEnabled;
    }

