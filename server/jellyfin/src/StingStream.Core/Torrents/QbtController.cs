    /// <summary>The torrent list, optionally filtered by category.</summary>
    [HttpGet("torrents/info")]
    public IActionResult Info([FromQuery] string? category, [FromQuery] string? hashes)
    {
        var unauthorised = Unauthorised();
        if (unauthorised is not null)
        {
            return unauthorised;
        }

        var views = _engine.List(string.IsNullOrWhiteSpace(category) ? null : category);

        if (!string.IsNullOrWhiteSpace(hashes) && !string.Equals(hashes, "all", StringComparison.OrdinalIgnoreCase))
        {
            var wanted = hashes.Split('|', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .ToHashSet(StringComparer.OrdinalIgnoreCase);
            views = views.Where(v => wanted.Contains(v.Hash)).ToList();
        }

        var array = new JsonArray();
        foreach (var view in views)
        {
            array.Add(ToQbtTorrent(view));
        }

        return new JsonResult(array);
    }

    /// <summary>General properties of one torrent.</summary>
    [HttpGet("torrents/properties")]
    public IActionResult Properties([FromQuery] string hash)
    {
        var unauthorised = Unauthorised();
        if (unauthorised is not null)
        {
            return unauthorised;
        }

        var view = _engine.Find(hash);
        if (view is null)
        {
            // qBittorrent answers 404 here, and the arrs use exactly that to decide whether a
            // just-added torrent has landed yet.
            return NotFound();
        }

        return new JsonResult(new JsonObject
        {
            ["hash"] = view.Hash,
            ["save_path"] = view.SavePath,
            ["name"] = view.Name,
            ["total_size"] = view.Size,
            ["total_downloaded"] = view.Downloaded,
            ["total_uploaded"] = view.Uploaded,
            ["dl_speed"] = view.DownloadRate,
            ["up_speed"] = view.UploadRate,
            ["seeding_time"] = view.SeedingSeconds,
            ["share_ratio"] = view.Ratio,
            ["addition_date"] = view.AddedOn,
            ["completion_date"] = view.Complete ? view.AddedOn : -1,
            ["eta"] = Eta(view),
            ["nb_connections"] = 0,
            ["piece_size"] = 0,
        });
    }

    /// <summary>The files inside one torrent.</summary>
    [HttpGet("torrents/files")]
    public IActionResult Files([FromQuery] string hash)
    {
        var unauthorised = Unauthorised();
        if (unauthorised is not null)
        {
            return unauthorised;
        }

        var view = _engine.Find(hash);
        if (view is null)
        {
            return NotFound();
        }

        var array = new JsonArray();
        for (var i = 0; i < view.Files.Count; i++)
        {
            var f = view.Files[i];
            array.Add(new JsonObject
            {
                ["index"] = i,
                ["name"] = f.Path,
                ["size"] = f.Size,
                ["progress"] = view.Progress,
                ["priority"] = 1,
                ["is_seed"] = view.Complete,
            });
        }

        return new JsonResult(array);
    }

    /// <summary>
    /// Add torrents, by URL/magnet or as uploaded <c>.torrent</c> files.
    /// </summary>
    /// <remarks>
    /// The arrs use both shapes: <c>AddFromMagnetLink</c> posts a magnet in <c>urls</c>, while
    /// <c>AddFromTorrentFile</c> downloads the .torrent itself and posts the bytes as a multipart
    /// <c>torrents</c> file.
    /// </remarks>
    [HttpPost("torrents/add")]
    [RequestSizeLimit(64 * 1024 * 1024)]
    public async Task<IActionResult> Add(CancellationToken cancellationToken)
    {
        var unauthorised = Unauthorised();
        if (unauthorised is not null)
        {
            return unauthorised;
        }

        if (!Request.HasFormContentType)
        {
            return Content("Fails.", "text/plain");
        }

        var form = await Request.ReadFormAsync(cancellationToken).ConfigureAwait(false);
        var category = form["category"].ToString();
        var savePath = form["savepath"].ToString();
        // qBittorrent renamed this parameter at Web API 2.11.0; we report 2.9.3, so the arrs send
        // "paused" -- but accepting both costs nothing and makes the shim usable by other clients.
        var paused = IsTrue(form["paused"]) || IsTrue(form["stopped"]);

        var resolved = ResolveSavePath(savePath, category);
        if (resolved is null)
        {
            return Content("Fails.", "text/plain");
        }

        savePath = resolved;

        var added = new List<string>();

        foreach (var file in form.Files)
        {
            if (file.Length == 0)
            {
                continue;
            }

            using var ms = new MemoryStream();
            await file.CopyToAsync(ms, cancellationToken).ConfigureAwait(false);
            try
            {
                added.Add(await _engine
                    .AddTorrentFileAsync(ms.ToArray(), category, savePath, paused, cancellationToken)
                    .ConfigureAwait(false));
            }
            catch (Exception ex) when (ex is TorrentException or IOException or InvalidOperationException)
            {
                _logger.LogError(ex, "Could not add the uploaded torrent {File}", file.FileName);
                return Content("Fails.", "text/plain");
            }
        }

        var urls = form["urls"].ToString();
        if (!string.IsNullOrWhiteSpace(urls))
        {
            foreach (var url in urls.Split(
                         new[] { '\n', '\r' },
                         StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                try
                {
                    added.Add(await _engine
                        .AddUrlAsync(url, category, savePath, paused, cancellationToken)
                        .ConfigureAwait(false));
                }
                catch (Exception ex) when (ex is TorrentException or IOException or System.Net.Http.HttpRequestException)
                {
                    _logger.LogError(ex, "Could not add the torrent URL");
                    return Content("Fails.", "text/plain");
                }
            }
        }

        if (added.Count == 0)
        {
            _logger.LogWarning("torrents/add carried neither a file nor a URL");
            return Content("Fails.", "text/plain");
        }

        // Make sure the category exists so a later torrents/categories reports it, which is what
        // the arrs' "Test" checks after creating one.
        if (!string.IsNullOrWhiteSpace(category))
        {
            await _engine.CreateCategoryAsync(category, savePath, cancellationToken).ConfigureAwait(false);
        }

        return Content("Ok.", "text/plain");
    }

    /// <summary>Remove torrents, optionally deleting their data.</summary>
    [HttpPost("torrents/delete")]
    public async Task<IActionResult> Delete(CancellationToken cancellationToken)
    {
        var unauthorised = Unauthorised();
        if (unauthorised is not null)
        {
            return unauthorised;
        }

        var form = await Request.ReadFormAsync(cancellationToken).ConfigureAwait(false);
        // Absent means false. The arrs omit the field entirely when keeping data, and treating
        // absence as "delete" would destroy a download that was only meant to stop seeding.
        var deleteFiles = IsTrue(form["deleteFiles"]);

        foreach (var hash in SplitHashes(form["hashes"]))
        {
            await _engine.RemoveAsync(hash, deleteFiles, cancellationToken).ConfigureAwait(false);
        }

        return Ok();
    }

