/// <summary>
/// A qBittorrent-compatible API subset, so Radarr and Sonarr can drive StingStream's in-process
/// torrent engine with their own stock, unpatched qBittorrent download client.
/// </summary>
/// <remarks>
/// Served at <c>/stingstream/qbt/api/v2/*</c> -- which, because Jellyfin maps every route under its
/// <c>BaseUrl</c>, is really <c>/jellyfin/stingstream/qbt/api/v2/*</c>. The supervisor writes that
/// whole prefix into <c>runtime.json</c> as <c>qbittorrent.url_base</c>, and
/// <see cref="Arr.OmniarrSyncService"/> configures both apps with it.
///
/// The surface is exactly what Radarr's and Sonarr's <c>QBittorrentProxyV2</c> actually calls,
/// verified against <c>server/radarr/src/NzbDrone.Core/Download/Clients/QBittorrent/</c>. Three
/// details in there are load-bearing and easy to get wrong:
///
/// * <c>app/webapiVersion</c> must answer *without* authentication and must not 404. That single
///   response is how the arrs choose the v2 proxy over the ancient v1 one, and the body has to
///   parse with .NET's <c>Version.Parse</c> -- no "v" prefix, no extra text.
/// * A completed torrent's <c>content_path</c> must differ from its <c>save_path</c>. When they
///   match, both apps mark the download as a *warning* and never import it.
/// * The <c>state</c> string drives everything: <c>stoppedUP</c>/<c>uploading</c> mean "ready to
///   import", <c>stalledDL</c> means "warn the user". <see cref="QbtState"/> holds the mapping.
///
/// Authentication is qBittorrent's own: a form login that returns an opaque <c>SID</c> cookie.
/// The credentials are generated by the supervisor and live in <c>runtime.json</c>.
/// </remarks>
[ApiController]
[AllowAnonymous]
[Route("stingstream/qbt/api/v2")]
[ApiExplorerSettings(IgnoreApi = true)]
public sealed class QbtController : ControllerBase
{
    /// <summary>Named <see cref="System.Net.Http.IHttpClientFactory"/> client for fetching .torrent URLs.</summary>
    public const string HttpClientName = "StingStream.Qbt";

    /// <summary>
    /// The Web API version reported to the arrs.
    /// </summary>
    /// <remarks>
    /// Chosen deliberately. Above 2.6.1, so the arrs use <c>content_path</c> to locate a finished
    /// download rather than reconstructing it from <c>torrents/files</c>; above 2.8.1, so share
    /// limits ride along on the add; and below 2.11.0, where qBittorrent renamed the add form's
    /// <c>paused</c> parameter to <c>stopped</c> and the arrs switch with it.
    /// </remarks>
    public const string WebApiVersion = "2.9.3";

    /// <summary>The application version reported to the arrs. Display only; nothing parses it.</summary>
    public const string AppVersion = "v4.6.7";

    /// <summary>Cookie name qBittorrent uses for its session. The arrs replay whatever we set.</summary>
    public const string SessionCookie = "SID";

    private readonly TorrentEngine _engine;
    private readonly QbtSessionStore _sessions;
    private readonly INodeRuntimeProvider _runtime;
    private readonly ILogger<QbtController> _logger;

    public QbtController(
        TorrentEngine engine,
        QbtSessionStore sessions,
        INodeRuntimeProvider runtime,
        ILogger<QbtController> logger)
    {
        _engine = engine;
        _sessions = sessions;
        _runtime = runtime;
        _logger = logger;
    }

    // --- authentication ----------------------------------------------------

    /// <summary>qBittorrent's form login.</summary>
    [HttpPost("auth/login")]
    [Consumes("application/x-www-form-urlencoded", "multipart/form-data")]
    public IActionResult Login([FromForm] string? username, [FromForm] string? password)
    {
        var creds = _runtime.Current?.Qbittorrent;
        if (creds is null)
        {
            _logger.LogWarning("A qBittorrent login arrived but runtime.json has no credentials");
            return Content("Fails.", "text/plain");
        }

        // Ordinal comparison, no trimming: these are generated secrets, not user input.
        var ok = string.Equals(username, creds.Username, StringComparison.Ordinal)
            && string.Equals(password, creds.Password, StringComparison.Ordinal);
        if (!ok)
        {
            _logger.LogWarning("Rejected a qBittorrent login for user {User}", username);
            return Content("Fails.", "text/plain");
        }

        var sid = _sessions.Create();
        Response.Cookies.Append(
            SessionCookie,
            sid,
            new CookieOptions
            {
                Path = "/",
                HttpOnly = true,
                // The arrs reach this over loopback HTTP; marking the cookie Secure would stop it
                // being sent back at all.
                Secure = false,
                SameSite = SameSiteMode.Lax,
            });
        return Content("Ok.", "text/plain");
    }

    /// <summary>Ends a session. qBittorrent has this; the arrs never call it.</summary>
    [HttpPost("auth/logout")]
    public IActionResult Logout()
    {
        if (Request.Cookies.TryGetValue(SessionCookie, out var sid))
        {
            _sessions.Remove(sid);
        }

        return Content("Ok.", "text/plain");
    }

    /// <summary>
    /// Reports whether this request carries a valid session.
    /// </summary>
    /// <remarks>
    /// Returns 403, never 401. The arrs treat a 403 as "log in again and retry" and a 401 as a
    /// hard authentication failure that aborts the whole operation.
    /// </remarks>
    private bool Authenticated()
    {
        var creds = _runtime.Current?.Qbittorrent;
        if (creds is null || string.IsNullOrEmpty(creds.Password))
        {
            // **Fail closed.** This used to return true, on the reasoning that qBittorrent itself
            // treats an empty username and password as "no authentication". qBittorrent is a
            // program a person installed and configured; this is a shim that is always configured,
            // by the supervisor, in runtime.json. So the only ways to reach this branch are that
            // runtime.json is missing, unreadable, or has not been written yet -- and every one of
            // those is a *fault*, not a decision, and the thing on the other side of it is
            // "add any torrent, to any path, and delete files". A fault must not open the door.
            //
            // The cost of being wrong the other way is small and loud: the arrs log a failed
            // download-client test and the supervisor's log says why.
            _logger.LogWarning(
                "Refusing a qBittorrent API call: runtime.json has no credentials for it yet");
            return false;
        }

        return Request.Cookies.TryGetValue(SessionCookie, out var sid) && _sessions.IsValid(sid);
    }

    /// <summary>
    /// The save path to use for an add, or null when the caller asked for one it may not have.
    /// </summary>
    /// <remarks>
    /// <c>savepath</c> arrives from the caller and used to be handed to MonoTorrent verbatim, which
    /// made this endpoint an arbitrary-file-write primitive: an add with
    /// <c>savepath=C:\Windows\System32</c> would have MonoTorrent create directories and write
    /// torrent contents there, as whatever account the node runs as. The arrs only ever send a path
    /// the node itself told them about, so nothing legitimate is lost by requiring it to be inside
    /// the torrent root.
    ///
    /// <see cref="SafePath.IsUnder"/> is the same containment check the federated materializer uses
    /// on peer-supplied titles, and for the same reason: it canonicalises both sides before
    /// comparing, so <c>..</c>, a symlink, a UNC path and a short 8.3 name all resolve to what they
    /// really are first.
    /// </remarks>
    private string? ResolveSavePath(string? requested, string? category)
    {
        if (string.IsNullOrWhiteSpace(requested))
        {
            return _engine.SavePathFor(category);
        }

        if (!SafePath.IsUnder(_engine.Root, requested))
        {
            _logger.LogWarning(
                "Refusing a qBittorrent add with a save path outside the torrent root: {Path}",
                requested);
            return null;
        }

        return requested;
    }

    private IActionResult? Unauthorised()
        => Authenticated() ? null : StatusCode(StatusCodes.Status403Forbidden, "Forbidden");

