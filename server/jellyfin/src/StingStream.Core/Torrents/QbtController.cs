    private static JsonObject ToQbtTorrent(TorrentView view) => new()
    {
        ["hash"] = view.Hash,
        ["name"] = view.Name,
        ["size"] = view.Size,
        ["total_size"] = view.Size,
        ["progress"] = view.Progress,
        ["eta"] = Eta(view),
        ["state"] = QbtState.From(view),
        ["category"] = view.Category,
        // The arrs still read the pre-3.x "label" when "category" is blank; sending both costs
        // nothing and makes the shim work with older tooling too.
        ["label"] = view.Category,
        ["tags"] = view.Tags,
        ["save_path"] = view.SavePath,
        ["content_path"] = view.ContentPath,
        ["ratio"] = view.Ratio,
        // -2 means "use the global limit", which app/preferences reports as disabled. Anything
        // >= 0 here would be read as a per-torrent limit the arrs then wait to be reached.
        ["ratio_limit"] = -2,
        ["seeding_time"] = view.SeedingSeconds,
        ["seeding_time_limit"] = -2,
        ["inactive_seeding_time_limit"] = -2,
        ["last_activity"] = DateTimeOffset.UtcNow.ToUnixTimeSeconds(),
        ["added_on"] = view.AddedOn,
        ["completion_on"] = view.Complete ? view.AddedOn : 0,
        ["dlspeed"] = view.DownloadRate,
        ["upspeed"] = view.UploadRate,
        ["downloaded"] = view.Downloaded,
        ["uploaded"] = view.Uploaded,
        ["amount_left"] = view.Remaining,
        ["completed"] = view.Size - view.Remaining,
        ["num_seeds"] = 0,
        ["num_leechs"] = 0,
        ["priority"] = 0,
        ["force_start"] = false,
        ["auto_tmm"] = false,
    };

    /// <summary>
    /// Seconds remaining, in qBittorrent's terms.
    /// </summary>
    /// <remarks>
    /// 8640000 (100 days) is qBittorrent's sentinel for "unknown or not applicable", and the arrs
    /// special-case exactly that value to mean "no estimate" rather than "100 days to go".
    /// </remarks>
    private static long Eta(TorrentView view)
    {
        const long Unknown = 8_640_000;
        if (view.Complete || view.Remaining <= 0)
        {
            return Unknown;
        }

        if (view.DownloadRate <= 0)
        {
            return Unknown;
        }

        var seconds = view.Remaining / view.DownloadRate;
        return seconds is <= 0 or > Unknown ? Unknown : seconds;
    }

    private static IEnumerable<string> SplitHashes(Microsoft.Extensions.Primitives.StringValues value)
        => value.ToString()
            .Split('|', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(h => h.ToLowerInvariant());

    private static bool IsTrue(Microsoft.Extensions.Primitives.StringValues value)
    {
        var s = value.ToString();
        return string.Equals(s, "true", StringComparison.OrdinalIgnoreCase)
            || string.Equals(s, "1", StringComparison.Ordinal);
    }

    internal static string Invariant(long value) => value.ToString(CultureInfo.InvariantCulture);
}

/// <summary>
/// Maps MonoTorrent's <see cref="TorrentState"/> onto the qBittorrent state strings the arrs
/// switch on.
/// </summary>
/// <remarks>
/// The mapping matters more than it looks. Radarr's and Sonarr's <c>GetItems</c> turn these
/// strings into a <c>DownloadItemStatus</c>, and only <c>Completed</c> triggers an import:
/// <c>uploading</c>, <c>stalledUP</c>, <c>queuedUP</c>, <c>forcedUP</c>, <c>pausedUP</c> and
/// <c>stoppedUP</c> all mean "done". <c>stalledDL</c> and <c>missingFiles</c> surface as warnings
/// the user sees, so they are reserved for states that really are stuck.
/// </remarks>
public static class QbtState
{
    /// <summary>The qBittorrent state string for a torrent.</summary>
    public static string From(TorrentView view)
    {
        if (view.State == TorrentState.Error)
        {
            return "error";
        }

        if (view.Complete)
        {
            return view.State switch
            {
                TorrentState.Seeding => view.UploadRate > 0 ? "uploading" : "stalledUP",
                TorrentState.Paused or TorrentState.Stopped or TorrentState.Stopping => "stoppedUP",
                TorrentState.Hashing or TorrentState.HashingPaused => "checkingUP",
                _ => "stoppedUP",
            };
        }

        return view.State switch
        {
            TorrentState.Downloading => "downloading",
            TorrentState.Seeding => "uploading",
            TorrentState.Hashing or TorrentState.HashingPaused => "checkingDL",
            TorrentState.FetchingHashes => "checkingDL",
            // Waiting on metadata from a magnet link. The arrs map this to Queued when DHT is on
            // and to a warning when it is off, which is exactly right: with DHT off a trackerless
            // magnet is never going to resolve.
            TorrentState.Metadata => "metaDL",
            TorrentState.Paused => "pausedDL",
            TorrentState.Stopped or TorrentState.Stopping => "stoppedDL",
            TorrentState.Starting => "queuedDL",
            _ => "downloading",
        };
    }
}
